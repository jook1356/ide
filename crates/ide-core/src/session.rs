//! Sessions: one agent run = (profile, repo, worktree, agent kind). Persisted without scrollback.

use std::fmt;
use std::path::PathBuf;
use std::sync::atomic::{AtomicU64, Ordering};

use serde::{Deserialize, Serialize};

use crate::error::{Error, Result};
use crate::paths::{Paths, now_unix, read_json, write_json};

/// Short, lexicographically sortable session id: 9 base36 chars of Unix milliseconds
/// (strictly increasing within a process) followed by 2 base36 chars of per-process entropy.
/// Safe for directory names and git branch names (`ide/<id>`).
#[derive(Debug, Clone, PartialEq, Eq, PartialOrd, Ord, Hash, Serialize, Deserialize)]
#[serde(try_from = "String", into = "String")]
pub struct SessionId(String);

const ID_TIME_LEN: usize = 9;
const ID_SUFFIX_LEN: usize = 2;

impl SessionId {
    /// Generate a new id. Ids generated by one process are strictly increasing.
    #[allow(clippy::new_without_default)]
    pub fn new() -> Self {
        static LAST_MS: AtomicU64 = AtomicU64::new(0);
        let now = std::time::SystemTime::now()
            .duration_since(std::time::UNIX_EPOCH)
            .unwrap_or_default();
        let now_ms = now.as_millis() as u64;
        let mut prev = LAST_MS.load(Ordering::Relaxed);
        let ms = loop {
            let next = now_ms.max(prev + 1);
            match LAST_MS.compare_exchange_weak(prev, next, Ordering::Relaxed, Ordering::Relaxed) {
                Ok(_) => break next,
                Err(p) => prev = p,
            }
        };
        let entropy = (u64::from(std::process::id()).wrapping_mul(0x9E37_79B9_7F4A_7C15)
            ^ u64::from(now.subsec_nanos()))
            % 36u64.pow(ID_SUFFIX_LEN as u32);
        let mut s = base36(ms, ID_TIME_LEN);
        s.push_str(&base36(entropy, ID_SUFFIX_LEN));
        SessionId(s)
    }

    /// Parse an existing id: 1..=32 chars of `[0-9a-z]`.
    pub fn parse(s: &str) -> Result<Self> {
        if s.is_empty()
            || s.len() > 32
            || !s
                .bytes()
                .all(|b| b.is_ascii_digit() || b.is_ascii_lowercase())
        {
            return Err(Error::InvalidSessionId(s.to_owned()));
        }
        Ok(SessionId(s.to_owned()))
    }

    /// The id as a string.
    pub fn as_str(&self) -> &str {
        &self.0
    }

    /// The git branch for this session: `ide/<id>`.
    pub fn branch(&self) -> String {
        format!("ide/{}", self.0)
    }
}

fn base36(mut n: u64, width: usize) -> String {
    const DIGITS: &[u8; 36] = b"0123456789abcdefghijklmnopqrstuvwxyz";
    let mut buf = vec![b'0'; width];
    for slot in buf.iter_mut().rev() {
        *slot = DIGITS[(n % 36) as usize];
        n /= 36;
    }
    String::from_utf8(buf).expect("ascii")
}

impl fmt::Display for SessionId {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(&self.0)
    }
}

impl TryFrom<String> for SessionId {
    type Error = Error;
    fn try_from(s: String) -> Result<Self> {
        Self::parse(&s)
    }
}

impl From<SessionId> for String {
    fn from(id: SessionId) -> String {
        id.0
    }
}

/// Which program a session runs.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum AgentKind {
    /// Claude Code (`claude`).
    Claude,
    /// OpenAI Codex CLI (`codex`).
    Codex,
    /// A plain shell (`cmd.exe` / `$SHELL`).
    Shell,
}

impl AgentKind {
    /// All kinds, for pickers.
    pub const ALL: [AgentKind; 3] = [AgentKind::Claude, AgentKind::Codex, AgentKind::Shell];

    /// Human-readable label.
    pub fn label(self) -> &'static str {
        match self {
            AgentKind::Claude => "Claude",
            AgentKind::Codex => "Codex",
            AgentKind::Shell => "Shell",
        }
    }
}

/// A persisted session.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Session {
    /// Unique id.
    pub id: SessionId,
    /// Display title.
    pub title: String,
    /// Profile name.
    pub profile: String,
    /// Main checkout of the repository the worktree belongs to.
    pub repo_path: PathBuf,
    /// The session's own worktree (agent cwd).
    pub worktree_path: PathBuf,
    /// The worktree's branch (`ide/<id>`).
    pub branch: String,
    /// Program to run.
    pub agent: AgentKind,
    /// Creation time, Unix seconds.
    pub created_at: u64,
    /// Last activity, Unix seconds.
    pub last_active: u64,
}

impl Session {
    /// Build a session for a freshly created worktree; timestamps are set to now.
    pub fn new(
        id: SessionId,
        title: impl Into<String>,
        profile: impl Into<String>,
        repo: &crate::repo::Repo,
        worktree: crate::worktree::Worktree,
        agent: AgentKind,
    ) -> Self {
        let now = now_unix();
        Session {
            id,
            title: title.into(),
            profile: profile.into(),
            repo_path: repo.root().to_path_buf(),
            worktree_path: worktree.path,
            branch: worktree.branch,
            agent,
            created_at: now,
            last_active: now,
        }
    }
}

/// Runtime state of a session's process. Never persisted.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub enum SessionStatus {
    /// Spawn in progress (or not yet started after app restart).
    #[default]
    Starting,
    /// The process is alive.
    Running,
    /// The process exited with this code.
    Exited(u32),
}

#[derive(Debug, Default, Serialize, Deserialize)]
struct SessionsFile {
    sessions: Vec<Session>,
}

/// Persistent session list backed by `sessions.json`. Every mutation saves immediately.
#[derive(Debug)]
pub struct SessionStore {
    paths: Paths,
    sessions: Vec<Session>,
}

impl SessionStore {
    /// Load `sessions.json` (empty if missing).
    pub fn open(paths: &Paths) -> Result<Self> {
        let file: SessionsFile = read_json(&paths.sessions_file())?.unwrap_or_default();
        Ok(Self {
            paths: paths.clone(),
            sessions: file.sessions,
        })
    }

    /// All sessions in insertion (= creation) order.
    pub fn list(&self) -> &[Session] {
        &self.sessions
    }

    /// Look up a session.
    pub fn get(&self, id: &SessionId) -> Option<&Session> {
        self.sessions.iter().find(|s| &s.id == id)
    }

    /// Add a session, or replace the stored one with the same id.
    pub fn upsert(&mut self, session: Session) -> Result<()> {
        match self.sessions.iter_mut().find(|s| s.id == session.id) {
            Some(slot) => *slot = session,
            None => self.sessions.push(session),
        }
        self.save()
    }

    /// Remove a session from the list (its worktree is not touched).
    pub fn remove(&mut self, id: &SessionId) -> Result<Session> {
        let idx = self
            .sessions
            .iter()
            .position(|s| &s.id == id)
            .ok_or_else(|| Error::SessionNotFound(id.to_string()))?;
        let s = self.sessions.remove(idx);
        self.save()?;
        Ok(s)
    }

    /// Set `last_active` to now.
    pub fn touch(&mut self, id: &SessionId) -> Result<()> {
        self.modify(id, |s| s.last_active = now_unix())
    }

    /// Change a session's title.
    pub fn set_title(&mut self, id: &SessionId, title: impl Into<String>) -> Result<()> {
        let title = title.into();
        self.modify(id, |s| s.title = title)
    }

    /// Point every session using profile `old` at `new` (after [`crate::ProfileStore::rename`]).
    pub fn rename_profile(&mut self, old: &str, new: &str) -> Result<()> {
        let mut changed = false;
        for s in self.sessions.iter_mut().filter(|s| s.profile == old) {
            s.profile = new.to_owned();
            changed = true;
        }
        if changed { self.save() } else { Ok(()) }
    }

    fn modify(&mut self, id: &SessionId, f: impl FnOnce(&mut Session)) -> Result<()> {
        let s = self
            .sessions
            .iter_mut()
            .find(|s| &s.id == id)
            .ok_or_else(|| Error::SessionNotFound(id.to_string()))?;
        f(s);
        self.save()
    }

    fn save(&self) -> Result<()> {
        #[derive(Serialize)]
        struct Out<'a> {
            sessions: &'a [Session],
        }
        write_json(
            &self.paths.sessions_file(),
            &Out {
                sessions: &self.sessions,
            },
        )
    }
}

#[cfg(test)]
pub(crate) fn sample_session(agent: AgentKind, worktree: PathBuf) -> Session {
    let id = SessionId::new();
    Session {
        branch: id.branch(),
        id,
        title: "t".into(),
        profile: "default".into(),
        repo_path: PathBuf::from("repo"),
        worktree_path: worktree,
        agent,
        created_at: 1,
        last_active: 1,
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::paths::test_util::TempDir;

    #[test]
    fn ids_are_short_sortable_unique() {
        let ids: Vec<_> = (0..1000).map(|_| SessionId::new()).collect();
        for w in ids.windows(2) {
            assert!(w[0] < w[1], "{} !< {}", w[0], w[1]);
        }
        let id = &ids[0];
        assert_eq!(id.as_str().len(), ID_TIME_LEN + ID_SUFFIX_LEN);
        assert_eq!(SessionId::parse(id.as_str()).unwrap(), *id);
        assert_eq!(id.branch(), format!("ide/{id}"));
        assert!(SessionId::parse("").is_err());
        assert!(SessionId::parse("ABC").is_err());
        assert!(SessionId::parse("a/b").is_err());
        assert_eq!(base36(35, 3), "00z");
        assert_eq!(base36(36, 3), "010");
    }

    #[test]
    fn store_round_trip() {
        let t = TempDir::new("sess");
        let paths = Paths::new(&t.0);
        let mut store = SessionStore::open(&paths).unwrap();
        assert!(store.list().is_empty());

        let a = sample_session(AgentKind::Claude, t.0.join("wa"));
        let b = sample_session(AgentKind::Shell, t.0.join("wb"));
        store.upsert(a.clone()).unwrap();
        store.upsert(b.clone()).unwrap();
        store.set_title(&a.id, "renamed").unwrap();
        store.touch(&b.id).unwrap();
        store.rename_profile("default", "work").unwrap();
        assert!(store.get(&b.id).unwrap().last_active > 1);

        let reopened = SessionStore::open(&paths).unwrap();
        assert_eq!(reopened.list(), store.list());
        assert_eq!(reopened.get(&a.id).unwrap().title, "renamed");
        assert_eq!(reopened.get(&a.id).unwrap().profile, "work");
        assert_eq!(reopened.get(&b.id).unwrap().agent, AgentKind::Shell);

        let mut store = reopened;
        store.remove(&a.id).unwrap();
        assert!(matches!(
            store.remove(&a.id),
            Err(Error::SessionNotFound(_))
        ));
        assert_eq!(SessionStore::open(&paths).unwrap().list().len(), 1);

        let json = std::fs::read_to_string(paths.sessions_file()).unwrap();
        assert!(json.contains("\"agent\": \"shell\""), "{json}");
    }

    #[test]
    fn bad_id_in_file_is_rejected() {
        let t = TempDir::new("sess-bad");
        let paths = Paths::new(&t.0);
        std::fs::write(
            paths.sessions_file(),
            r#"{"sessions":[{"id":"../x","title":"","profile":"default","repo_path":"r","worktree_path":"w","branch":"b","agent":"claude","created_at":0,"last_active":0}]}"#,
        )
        .unwrap();
        assert!(matches!(
            SessionStore::open(&paths),
            Err(Error::Json { .. })
        ));
    }
}
